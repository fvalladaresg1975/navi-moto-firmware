"""Writes hal/esp32/navi_build.c with this build's date before compiling.

The phone app looks for this string in a .bin before a WiFi update (hal/esp32/navi_ota.cpp):
"ota1" means the firmware can itself receive updates over WiFi - sending one that can't
would leave the USB cable as the only way back. The date is shown in the app and in the
board's "Acerca de". Only rewritten when the text changes, so only this file recompiles.
"""
import datetime
import os

Import("env")  # noqa: F821 - provided by PlatformIO

path = os.path.join(env.subst("$PROJECT_DIR"), "hal", "esp32", "navi_build.c")  # noqa: F821
stamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
src = (
    "/* Generated by support/navi_build_stamp.py on every build - don't edit, not in git. */\n"
    "const char navi_build_stamp[] = \"NAVIMOTO-FW ota1 " + stamp + "\";\n"
)
old = None
if os.path.exists(path):
    with open(path, encoding="utf-8") as f:
        old = f.read()
if old != src:
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(src)
